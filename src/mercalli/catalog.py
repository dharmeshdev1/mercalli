"""The list of services Mercalli watches.

`catalog/seed.yaml` is written by people: a name, a category, a guess at the status page and the
domains customers use. `catalog/services.yaml` is written by `mercalli catalog discover`: every
seed entry that was verified against a live status page, plus status pages found automatically
among the most visited domains on the web.
"""

from __future__ import annotations

import re
from functools import lru_cache
from importlib import resources
from pathlib import Path

import yaml
from pydantic import BaseModel, Field

from mercalli.domain import Category

# Adapters that understand a vendor's status page. "statuspage" covers Atlassian Statuspage and the
# hosted products that copy its API (incident.io, for example).
ADAPTERS = ("statuspage", "statusio", "aws", "gcp", "azure", "slack", "heroku")


class SeedEntry(BaseModel):
    name: str
    category: Category
    status: str
    domains: list[str] = Field(default_factory=list)
    id: str | None = None
    adapter: str | None = None

    @property
    def slug(self) -> str:
        return self.id or slugify(self.name)


class Service(BaseModel):
    """A verified service with a working status page adapter."""

    id: str
    name: str
    category: Category
    adapter: str
    base_url: str
    domains: list[str] = Field(default_factory=list)
    page_id: str | None = None
    flavor: str | None = None  # "atlassian" or "compatible" for statuspage adapters
    history: bool = False  # True when the full incident history can be backfilled
    curated: bool = True  # False for pages discovered automatically
    rank: int | None = None  # Tranco rank of the main domain, when known


def slugify(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return s or "service"


def catalog_dir() -> Path:
    """The catalog directory, from a source checkout or from the installed package."""
    here = Path(__file__).resolve()
    for parent in here.parents:
        candidate = parent / "catalog"
        if (candidate / "seed.yaml").exists():
            return candidate
    return Path(str(resources.files("mercalli") / "_catalog"))


def load_seed(path: Path | None = None) -> list[SeedEntry]:
    path = path or catalog_dir() / "seed.yaml"
    raw = yaml.safe_load(path.read_text()) or []
    entries = [SeedEntry.model_validate(r) for r in raw]
    seen: set[str] = set()
    for e in entries:
        if e.slug in seen:
            raise ValueError(f"duplicate service id in seed: {e.slug}")
        seen.add(e.slug)
    return entries


@lru_cache(maxsize=4)
def _load_services(path: str) -> tuple[Service, ...]:
    p = Path(path)
    if not p.exists():
        return ()
    raw = yaml.safe_load(p.read_text()) or []
    return tuple(Service.model_validate(r) for r in raw)


def load_services(path: Path | None = None) -> list[Service]:
    path = path or catalog_dir() / "services.yaml"
    return list(_load_services(str(path)))


def load_excluded(path: Path | None = None) -> tuple[set[str], set[str]]:
    """Page ids and domains discovery must skip (see catalog/exclude.yaml)."""
    path = path or catalog_dir() / "exclude.yaml"
    if not path.exists():
        return set(), set()
    raw = yaml.safe_load(path.read_text()) or {}
    if isinstance(raw, list):  # the original format: a bare list of page ids
        return {str(x) for x in raw}, set()
    return {str(x) for x in raw.get("page_ids") or []}, {str(x).lower() for x in raw.get("domains") or []}


def is_excluded(service: Service, page_ids: set[str], domains: set[str]) -> bool:
    if service.page_id and service.page_id in page_ids:
        return True
    return any(d.lower() == x or d.lower().endswith("." + x) for d in service.domains for x in domains)


def write_services(services: list[Service], path: Path | None = None) -> None:
    path = path or catalog_dir() / "services.yaml"
    page_ids, domains = load_excluded()
    services = [s for s in services if not is_excluded(s, page_ids, domains)]
    rows = [s.model_dump(mode="json", exclude_none=True) for s in sorted(services, key=lambda s: s.id)]
    header = f"# Generated by `mercalli catalog discover`. Edit catalog/seed.yaml instead.\n# {len(rows)} services.\n"
    path.write_text(header + yaml.safe_dump(rows, sort_keys=False, width=120, allow_unicode=True))
    _load_services.cache_clear()
